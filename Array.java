public class Array {
    public static void main(String[] args) {
        //initializing the Array
        int[] arr = {1, 2, 3, 4, 5};
        //Size of an Array
        int n = arr.length;
        //traversing the Array
        for (int i = 0; i < n; i++)
        System.out.print(arr[i] + " " );
    }
}
